// Builds the static export for GitHub Pages into `out/`.
// Next can't export the proxy route handler (it needs a server), so its folder is parked outside
// `src/` during the build and always restored afterwards.
import { spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { mkdir, rename, rm } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const proxyDir = path.join(root, 'src', 'app', 'api', 'proxy')
const parkedDir = path.join(root, 'node_modules', '.cache', 'build-pages', 'proxy')
const nextBin = path.join(root, 'node_modules', 'next', 'dist', 'bin', 'next')
const basePath = process.env.PAGES_BASE_PATH ?? '/fumadocs-api-portal'

// A previous run killed mid-build may have left the folder parked.
// If the folder was also restored from git, the tracked copy wins.
if (existsSync(parkedDir)) {
  if (existsSync(proxyDir)) await rm(parkedDir, { recursive: true, force: true })
  else await rename(parkedDir, proxyDir)
}

// Ctrl+C reaches `next build` too; ignoring it here lets `finally` restore the folder.
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => {})

// Route types generated by earlier builds or `next dev` still point at the proxy route.
for (const types of ['types', 'dev/types'])
  await rm(path.join(root, '.next', types), { recursive: true, force: true })

await mkdir(path.dirname(parkedDir), { recursive: true })
await rename(proxyDir, parkedDir)
let status = 1
try {
  const result = spawnSync(process.execPath, [nextBin, 'build'], {
    cwd: root,
    stdio: 'inherit',
    env: {
      ...process.env,
      STATIC_EXPORT: '1',
      PAGES_BASE_PATH: basePath,
      NEXT_PUBLIC_BASE_PATH: basePath,
    },
  })
  status = result.status ?? 1
} finally {
  await rename(parkedDir, proxyDir)
}

process.exit(status)
